import { packageTextFiles } from "../shared/package-text-files.ts";
import { componentDependencyCss } from "../framework/component-catalog/index.ts";
import { cssLayer, fontImportRule, layerOrder, patternLayers, safeFontStylesheet } from "../css-layers/index.ts";
import { parseFrameworkSiteTheme, type FrameworkSiteTheme } from "../framework/site-theme/index.ts";
import { utilityCss } from "../utilities/index.ts";
import { formatCss } from "../code-editor/format.ts";
import type { PatternCompilation } from "./engine.ts";

export interface PatternExportTheme {
  /** Canonical starter stylesheet used by the application, not another token copy. */
  tokenCss: string;
  theme?: FrameworkSiteTheme | null;
}

const escapeHtml = (value: string) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");

/** The editor keeps local CSS; every export action consumes this complete bundle. */
export const compilePatternArtifacts = (compilation: PatternCompilation, context: PatternExportTheme) => {
  const theme = context.theme ? parseFrameworkSiteTheme(JSON.stringify(context.theme)) : null;
  const overrides = Object.entries(theme?.variables ?? {}).map(([name, value]) => `  ${name}: ${value};`).join("\n");
  const tokens = `${context.tokenCss.trim()}${overrides ? `\n\n:root {\n${overrides}\n}` : ""}`;
  const components = componentDependencyCss(compilation.definition.dependencies).join("\n\n");
  const fontStylesheet = safeFontStylesheet(theme?.fontStylesheet);
  const fontImport = fontStylesheet ? `${fontImportRule(fontStylesheet, "tokens")}\n\n` : "";
  const documentDefaults = `.pattern-document {\n  margin: 0;\n  color: var(--semantic-text);\n  background: var(--semantic-surface);\n  font-family: var(--font-body);\n}`;
  const stylesheet = `${layerOrder(patternLayers)}\n\n${fontImport}${formatCss([
    cssLayer("tokens", tokens),
    cssLayer("utilities", `${utilityCss}\n\n${documentDefaults}`),
    ...(components ? [cssLayer("components", components)] : []),
    cssLayer("patterns", compilation.css),
  ].join("\n\n"))}\n`;
  const css = `/* Generated by techies.tools. Shared defaults precede component overrides. */\n${stylesheet}`;
  const html = `<!doctype html>\n<html lang="en">\n<head>\n  <meta charset="utf-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1">\n  <title>${escapeHtml(compilation.definition.title)}</title>\n  <link rel="stylesheet" href="./${escapeHtml(compilation.state.exportName)}.css">\n</head>\n<body class="pattern-document">\n${compilation.html}\n</body>\n</html>\n`;
  return { css, html };
};

export const patternArtifactFiles = (compilation: PatternCompilation, context: PatternExportTheme) => {
  const artifacts = compilePatternArtifacts(compilation, context);
  return [
    { name: `${compilation.state.exportName}.css`, value: artifacts.css },
    { name: `${compilation.state.exportName}.html`, value: artifacts.html },
  ] as const;
};

export const packagePatternArtifacts = (compilation: PatternCompilation, context: PatternExportTheme) =>
  packageTextFiles(`${compilation.state.exportName}.zip`, patternArtifactFiles(compilation, context));
